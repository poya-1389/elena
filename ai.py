_NAME_PATTERN = re.compile(r"(?<!\w)(الن‌?ا|elena|ely|eli)(?!\w)", re.IGNORECASE)


def message_calls_elena(text: str) -> bool:
    if not text:
        return False
    return bool(_NAME_PATTERN.search(text))


def _format_author(name: str | None, username: str | None) -> str:
    if not name:
        return ""
    tag = f"@{username}" if username else ""
    return f"[{name}{' ' + tag if tag else ''}]: "


def _history_to_contents(history: list[dict]) -> list[types.Content]:
    contents: list[types.Content] = []
    for turn in history:
        role = "model" if turn["role"] == "model" else "user"
        prefix = _format_author(turn.get("author_name"), turn.get("author_username")) if role == "user" else ""
        contents.append(types.Content(role=role, parts=[types.Part(text=prefix + turn["content"])]))
    return contents


async def generate_reply_stream(
    history: list[dict],
    user_text: str,
    author_name: str | None = None,
    author_username: str | None = None,
    chat_kind: str = "private",
    mode: str = "default",
):
    """AsyncGenerator که تکه‌های متن تولیدشده را yield می‌کند."""
    if _client is None:
        raise RuntimeError("AI client not initialized")

    contents = _history_to_contents(history)
    prefix = _format_author(author_name, author_username)
    contents.append(types.Content(role="user", parts=[types.Part(text=prefix + user_text)]))

    chat_context_note = (
        "\n\n# وضعیت چت فعلی\n"
        + ("الان تو یک چت خصوصی (Private) با همین یک نفر هستی." if chat_kind == "private"
           else "الان تو یک گروه/سوپرگروه هستی — چند نفر ممکنه باهم صحبت کنن.")
    )

    persona = MODE_PROMPTS.get(mode, MODE_DEFAULT_PROMPT)
    system_instruction = persona + "\n\n" + TECHNICAL_ADDENDUM + chat_context_note

    config = types.GenerateContentConfig(
        system_instruction=system_instruction,
        temperature=0.95,
        max_output_tokens=800,
    )

    try:
        stream = await _client.aio.models.generate_content_stream(
            model=MODEL_NAME, contents=contents, config=config
        )
        async for chunk in stream:
            if chunk.text:
                yield chunk.text
    except Exception as exc:  # noqa: BLE001
        text = str(exc)
        if "429" in text or "RESOURCE_EXHAUSTED" in text:
            logger.warning("Gemini quota exhausted: %s", exc)
            yield "__ELENA_AI_QUOTA__"
        else:
            logger.exception("Gemini generation failed: %s", exc)
            yield "__ELENA_AI_ERROR__"
