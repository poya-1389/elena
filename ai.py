_NAME_PATTERN = re.compile(r"(?<!\w)(الن‌?ا|elena|ely|eli)(?!\w)", re.IGNORECASE)


def message_calls_elena(text: str) -> bool:
    """تشخیص صدا زدن النا با نام (با word boundary، برای جلوگیری از False Positive)."""
    if not text:
        return False
    return bool(_NAME_PATTERN.search(text))


def _history_to_contents(history: list[dict]) -> list[types.Content]:
    contents: list[types.Content] = []
    for turn in history:
        role = "model" if turn["role"] == "model" else "user"
        prefix = f"[{turn['author_name']}]: " if turn.get("author_name") and role == "user" else ""
        contents.append(
            types.Content(role=role, parts=[types.Part(text=prefix + turn["content"])])
        )
    return contents


async def generate_reply_stream(
    history: list[dict],
    user_text: str,
    author_name: str | None = None,
    media: list[tuple[bytes, str]] | None = None,
):
    """
    AsyncGenerator که تکه‌های متن تولیدشده را yield می‌کند (برای استریم در تلگرام).
    media: لیستی از (bytes, mime_type) برای عکس/صدا/PDF — Gemini این‌ها را به‌صورت
    بومی می‌فهمد، بدون نیاز به سرویس جداگانه‌ی OCR/STT.
    """
    if _client is None:
        raise RuntimeError("AI client not initialized")

    contents = _history_to_contents(history)

    parts: list[types.Part] = []
    prefix = f"[{author_name}]: " if author_name else ""
    parts.append(types.Part(text=prefix + user_text))
    for data, mime_type in media or []:
        parts.append(types.Part.from_bytes(data=data, mime_type=mime_type))

    contents.append(types.Content(role="user", parts=parts))

    config = types.GenerateContentConfig(
        system_instruction=SYSTEM_INSTRUCTION,
        temperature=0.95,
        max_output_tokens=800,
        # توجه: ابزار Google Search عمداً حذف شد. با فعال بودنش، Automatic
        # Function Calling باعث می‌شد هر پیام کاربر به‌جای ۱ درخواست، تا ۱۰
        # درخواست جداگانه به Gemini بزنه (هر بار که مدل تصمیم می‌گرفت جست‌وجو
        # کنه)، و همین سهمیه‌ی رایگان روزانه را چند برابر سریع‌تر از انتظار
        # مصرف می‌کرد. تا اطمینان از پایداری، غیرفعال ماند.
    )

    try:
        stream = await _client.aio.models.generate_content_stream(
            model=MODEL_NAME, contents=contents, config=config
        )
        async for chunk in stream:
            if chunk.text:
                yield chunk.text
    except Exception as exc:  # noqa: BLE001
        text = str(exc)
        if "429" in text or "RESOURCE_EXHAUSTED" in text:
            logger.warning("Gemini quota exhausted: %s", exc)
            yield "__ELENA_AI_QUOTA__"
        else:
            logger.exception("Gemini generation failed: %s", exc)
            yield "__ELENA_AI_ERROR__"
